#!/usr/bin/env python3
"""Title music: r25-intro.vgm (YM2612 + PSG, 1 wait per frame) -> music_data.c for the bare-metal menu player."""
import struct, sys
d = open("/home/claude/md-doom64kb/res/r25-intro.vgm", "rb").read()
assert d[:4] == b"Vgm "
start = 0x34 + struct.unpack("<I", d[0x34:0x38])[0]
loop = 0x1c + struct.unpack("<I", d[0x1c:0x20])[0]
data = d[start:]
out = sys.argv[1] if len(sys.argv) > 1 else "music_data.c"
with open(out, "w") as o:
    o.write("/* generated by gen_music.py */\nconst unsigned char intro_vgm[] = {\n")
    for i in range(0, len(data), 24): o.write(",".join(str(b) for b in data[i:i+24]) + ",\n")
    o.write("};\nconst unsigned short intro_vgm_loop = %d;\n" % (loop - start))
