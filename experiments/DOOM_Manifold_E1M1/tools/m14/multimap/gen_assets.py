#!/usr/bin/env python3
"""Menu assets: Doom TITLEPIC -> 16-colour 4bpp tiles, SGDK font tiles, vector stubs."""
import struct, sys
from PIL import Image
sys.path.insert(0, "/home/claude/md-doom64kb/experiments/DOOM_Manifold_E1M1/m01")
import wad_textures as WT

src = Image.open("/home/claude/md-doom64kb/assets/art/doom-title-md-32col.png")
sp = src.getpalette()[:96]
rgb = [tuple(sp[i*3:i*3+3]) for i in range(32)]
lv = lambda v: min(7, round(v / 36.4))
md = lambda c: (lv(c[2]) << 9) | (lv(c[1]) << 5) | (lv(c[0]) << 1)
pix = list(src.getdata())
import collections
X = collections.Counter(pix).most_common(1)[0][0]   # index 0 of both palettes (transparent = backdrop)
W, H = 320, 224
tiles_px = []
for ty in range(H//8):
    for tx in range(W//8):
        tiles_px.append([pix[(ty*8+y)*W + tx*8 + x] for y in range(8) for x in range(8)])
def d2(a, b): return sum((x-y)**2 for x, y in zip(rgb[a], rgb[b]))
# two 16-colour sub-palettes + per-tile choice (k-means style)
import random
random.seed(1)
assign = [random.randint(0, 1) for _ in tiles_px]
pals = [list(range(16)), list(range(16, 32))]
def tile_cost(t, pal):
    return sum(min(d2(c, p) for p in pal) for c in t)
for it in range(12):
    for k in (0, 1):
        cnt = {}
        for t, a in zip(tiles_px, assign):
            if a == k:
                for c in t: cnt[c] = cnt.get(c, 0) + 1
        # pick 16 colours greedily minimising weighted error
        chosen = [X]
        cand = list(cnt)
        while len(chosen) < min(16, len(cand) + 1):
            best = None
            for c in cand:
                if c in chosen: continue
                tr = chosen + [c]
                e = sum(n * min(d2(x, p) for p in tr) for x, n in cnt.items())
                if best is None or e < best[0]: best = (e, c)
            chosen.append(best[1])
        while len(chosen) < 16: chosen.append(chosen[0])
        assert chosen[0] == X
        pals[k] = chosen
    new_assign = [0 if tile_cost(t, pals[0]) <= tile_cost(t, pals[1]) else 1 for t in tiles_px]
    if new_assign == assign: break
    assign = new_assign
err = sum(min(tile_cost(t, pals[0]), tile_cost(t, pals[1])) for t in tiles_px)
print("total sq error", err)
cram = [md(rgb[c]) for k in (0, 1) for c in pals[k]]
tiles = []
for t, a in zip(tiles_px, assign):
    rows = []
    for y in range(8):
        row = 0
        for x in range(8):
            c = t[y*8+x]
            row = (row << 4) | min(range(16), key=lambda i: d2(c, pals[a][i]))
        rows.append(row)
    tiles.append(rows)
attrs = [a << 13 for a in assign]
# preview
pv = Image.new("RGB", (W, H)); pp = pv.load()
for n, (t, a) in enumerate(zip(tiles, assign)):
    tx, ty = n % 40, n // 40
    for y in range(8):
        for x in range(8):
            i = (t[y] >> (4*(7-x))) & 15
            pp[tx*8+x, ty*8+y] = rgb[pals[a][i]]
pv.save("/tmp/m14x/title_q16.png")
# SGDK font: 16x6 chars (ASCII 32..127), ink index 15 -> 1
f = Image.open("/home/claude/sgdkr/res/image/font_default.png")
fd = list(f.getdata())
font = []
for ci in range(96):
    cx, cy = (ci % 16) * 8, (ci // 16) * 8
    t = []
    for y in range(8):
        row = 0
        for x in range(8):
            row = (row << 4) | (1 if fd[(cy+y)*128 + cx + x] else 0)
        t.append(row)
    font.append(t)
with open("assets.c", "w") as o:
    o.write("/* generated by gen_assets.py */\n#include \"menu.h\"\n")
    o.write("const unsigned short title_attr[%d] = {" % len(attrs) + ",".join(str(x) for x in attrs) + "};\n")
    o.write("const unsigned short title_pal[32] = {" + ",".join("0x%04X" % c for c in cram) + "};\n")
    o.write("const unsigned long title_tiles[%d] = {\n" % (len(tiles)*8))
    o.write(",\n".join(",".join("0x%08X" % r for r in t) for t in tiles) + "};\n")
    o.write("const unsigned long font_tiles[%d] = {\n" % (len(font)*8))
    o.write(",\n".join(",".join("0x%08X" % r for r in t) for t in font) + "};\n")
print("tiles", len(tiles))
