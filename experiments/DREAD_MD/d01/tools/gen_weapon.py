#!/usr/bin/env python3
"""DREAD-MD: pistol view sprite from the WAD -> Mega Drive hardware sprite tiles (PAL1).

Frames (Doom S_PISTOL..): ready = PISGA0, fire = PISGB0 + flash PISFA0, PISGC0, PISGB0.
Doom places a weapon patch at screen (1 - leftoffset, 32 - topoffset) on the 320x168 view; we scale
that to our 256x112 view (x 0.8, y 2/3) and cut one common canvas into hardware sprites (<= 4x4 cells).

usage: gen_weapon.py WAD OUT.c
"""
import sys, math
from pathlib import Path
import numpy as np
sys.path.insert(0, str(Path(__file__).parent))
from conv import Wad, read_patch
import struct

VIEW_W, VIEW_H = 256, 112
SX, SY = VIEW_W / 320.0, VIEW_H / 168.0
FRAMES = [("PISGA0",), ("PISGB0", "PISFA0"), ("PISGC0",), ("PISGB0",)]


def main():
    wad = Wad(sys.argv[1])
    pal = np.frombuffer(wad.get("PLAYPAL")[:768], np.uint8).reshape(256, 3).astype(float)
    sprites = wad.range(("S_START", "SS_START"), ("S_END", "SS_END"))
    # compose each frame on a 320x200 canvas of palette indices (-1 = transparent)
    canv = []
    for parts in FRAMES:
        c = np.full((200, 320), -1, np.int16)
        for nm in parts:
            d = sprites[nm]
            w, h, lo, to = struct.unpack_from("<HHhh", d, 0)
            img = read_patch(d)
            x0, y0 = 1 - lo, 32 - to - 44      # raised so the hand shows above the bar (our view is 112 rows)
            for y in range(h):
                for x in range(w):
                    if img[y, x] >= 0 and 0 <= y0 + y < 200 and 0 <= x0 + x < 320:
                        c[y0 + y, x0 + x] = img[y, x]
        canv.append(c)
    # common bounding box (in our scaled coordinates), aligned to 8 pixels
    ys, xs = np.nonzero(np.any([c >= 0 for c in canv], axis=0))
    bx0, bx1 = int(xs.min() * SX) // 8 * 8, int(math.ceil((xs.max() + 1) * SX / 8)) * 8
    by0, by1 = int(ys.min() * SY) // 8 * 8, min(VIEW_H, int(math.ceil((ys.max() + 1) * SY / 8)) * 8)
    W, H = bx1 - bx0, by1 - by0
    # scaled frames (nearest sample of the 320x200 canvas)
    scaled = []
    for c in canv:
        s = np.full((H, W), -1, np.int16)
        for y in range(H):
            for x in range(W):
                s[y, x] = c[min(199, int((by0 + y + 0.5) / SY)), min(319, int((bx0 + x + 0.5) / SX))]
        scaled.append(s)
    # 15-colour palette (k-means over the used colours), index 0 transparent
    used = np.concatenate([s[s >= 0] for s in scaled])
    X = pal[used]
    rng = np.random.default_rng(1)
    C = X[rng.choice(len(X), 15, replace=False)]
    for _ in range(30):
        a = ((X[:, None] - C[None]) ** 2).sum(-1).argmin(1)
        for k in range(15):
            if (a == k).any(): C[k] = X[a == k].mean(0)
    lv = lambda v: int(max(0, min(7, round(v / 36.43))))
    md = [(0, 0, 0)] + [(lv(c[0]), lv(c[1]), lv(c[2])) for c in C]
    mdrgb = np.array([[l * 36.43 for l in c] for c in md])
    near = {}
    def q(i):
        if i not in near: near[i] = 1 + int(((mdrgb[1:] - pal[i]) ** 2).sum(-1).argmin())
        return near[i]
    # cut the canvas into sprites of up to 4x4 cells; tiles of each sprite in column-major order
    pieces = []
    for py in range(0, H, 32):
        for px in range(0, W, 32):
            pieces.append((px, py, min(32, W - px) // 8, min(32, H - py) // 8))
    tiles_per_frame = sum(w * h for _, _, w, h in pieces)
    out = []
    for s in scaled:
        words = []
        for px, py, wc, hc in pieces:
            for cx in range(wc):
                for cy in range(hc):
                    for y in range(8):
                        v = 0
                        for x in range(8):
                            i = s[py + cy * 8 + y, px + cx * 8 + x]
                            v = (v << 4) | (0 if i < 0 else q(int(i)))
                        words.append(v)
        out.append(words)
    o = ["/* generated by gen_weapon.py -- pistol view sprite */", '#include "mapdata.h"',
         "const uint16_t weap_pal[16] = {%s};" % ",".join("0x%03X" % ((c[2] * 2) << 8 | (c[1] * 2) << 4 | (c[0] * 2)) for c in md),
         "const uint16_t weap_x = %d, weap_y = %d, weap_tiles = %d, weap_nframes = %d, weap_npieces = %d;" % (bx0, by0, tiles_per_frame, len(out), len(pieces)),
         "const uint8_t weap_piece[%d][4] = {%s};" % (len(pieces), ",".join("{%d,%d,%d,%d}" % p for p in pieces)),
         "const uint32_t weap_data[%d] = {%s};" % (len(out) * len(out[0]), ",".join("0x%08X" % w for f in out for w in f))]
    Path(sys.argv[2]).write_text("\n".join(o) + "\n")
    print("weapon: canvas %dx%d at (%d,%d), %d pieces, %d tiles/frame" % (W, H, bx0, by0, len(pieces), tiles_per_frame))


if __name__ == "__main__":
    main()
