#!/usr/bin/env python3
"""Constant reciprocal tables for DREAD-MD D01 (ROM instead of RAM).
rcp4_tab[z] = 2^20 / z (z = 16..1023, saturated at 65535);
rcpf_tab[m][z] = 2^19 * FOCAL / 64 / z for FOCAL = 80, 40, 64, 32 (H40/H32 x row/column-doubled)."""
import sys
out = ["/* generated by tools/gen_tables.py */", "#include <types.h>"]
r4 = [min(65535, (1 << 20) // max(z, 16)) for z in range(1024)]
out.append("const u16 rcp4_tab[1024] = {%s};" % ",".join(map(str, r4)))
rows = []
for f in (80, 40, 64, 32):
    rows.append("{%s}" % ",".join(str(((1 << 19) // 64 * f) // max(z, 16)) for z in range(1024)))
out.append("const u16 rcpf_tab[4][1024] = {%s};" % ",".join(rows))
open(sys.argv[1], "w").write("\n".join(out) + "\n")
print("tables: rcp4 + 4 x rcpf")
