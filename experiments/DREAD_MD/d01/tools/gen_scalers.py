#!/usr/bin/env python3
"""Dread-style wall scalers for DREAD-MD D01.

One unrolled routine per quantised texel step z (texels per screen row): slot k (row k, k = 1 is the
top row) is a single  move.b  o_k(a1),k*4(a0)  (or move.w for the column-doubled modes, texels stored
as words) with o_k = round((k-1) * z).  The caller jumps to end - n*6 to draw rows n..1.
Also emits scal_q[]: zpp*1024 (16.16 zpp >> 6, < 32 texels/row) -> level."""
import math, sys

NL = 256
Z0, Z1 = 1.0 / 64, 32.0
R = (Z1 / Z0) ** (1.0 / (NL - 1))
NS_B, NS_W = 72, 144

out = ["/* generated by tools/gen_scalers.py */", "        .text", "        .globl scal_b, scal_w, scal_q"]
for name, ns, op, sc in (("b", NS_B, 0x1169, 1), ("w", NS_W, 0x3169, 2)):
    for q in range(NL):
        z = Z0 * R ** q
        words = []
        for k in range(ns, 0, -1):
            o = int(math.floor((k - 1) * z + 0.5)) * sc
            words.append("0x%04x,%d,%d" % (op, o, k * 4))
        for i in range(0, len(words), 8):
            out.append("        .word " + ",".join(words[i:i + 8]))
        out.append("s%s_%d:" % (name, q))
        out.append("        rts")
for name in ("b", "w"):
    out.append("        .even")
    out.append("scal_%s:" % name)
    for i in range(0, NL, 8):
        out.append("        .long " + ",".join("s%s_%d" % (name, q) for q in range(i, i + 8)))
qt = []
for i in range(32768):
    z = (i + 0.5) / 1024.0
    q = int(round(math.log(z / Z0) / math.log(R))) if z > 0 else 0
    qt.append(max(0, min(NL - 1, q)))
out.append("scal_q:")
for i in range(0, len(qt), 32):
    out.append("        .byte " + ",".join(str(x) for x in qt[i:i + 32]))
out.append("        .even")
open(sys.argv[1], "w").write("\n".join(out) + "\n")
print("scalers: %d levels, step ratio %.4f" % (NL, R))
