#!/usr/bin/env python3
"""Dread-style wall scalers for DREAD-MD D01.

One unrolled routine per quantised texel step z (texels per screen row): slot k (row k, k = 1 is the
top row) is a single  move.b  o_k(a1),k*4(a0)  (or move.w for the column-doubled modes, texels stored
as words) with o_k = round((k-1) * z).  The caller jumps to end - n*6 to draw rows n..1.
Also emits scal_q[]: zpp*1024 (16.16 zpp >> 6, < 32 texels/row) -> level."""
import math, sys, os

NL = 128
Z0, Z1 = 1.0 / 64, 32.0
R = (Z1 / Z0) ** (1.0 / (NL - 1))
FERRET=os.environ.get("DREAD_FERRET_RENDERER","0")=="1"
NS_B, NS_W = 72, (72 if FERRET else 144)

out = ["/* generated by tools/gen_scalers.py */", "        .text", "        .globl scal_b, scal_w, scal_f, scal_q"]
for name, ns, op, sc in (("b", NS_B, 0x1169, 1), ("w", NS_W, 0x1169, 1), ("f", NS_W, 0x1169, 1)):
    if FERRET and name=="f":continue
    for q in range(NL):
        z = Z0 * R ** q
        words = []
        for k in range(ns, 0, -1):
            o = int(math.floor((k - 1) * z + 0.5)) * sc
            words.append("0x%04x,%d,%d" % (op, o, k * 4))
            if name == "w": words.append("0x%04x,%d,%d" % (op, o, k * 4 + 1))   # column-doubled: same texel in both bytes
        for i in range(0, len(words), 8):
            out.append("        .word " + ",".join(words[i:i + 8]))
        out.append("s%s_%d:" % (name, q))
        out.append("        rts")
for name in ("b", "w", "f"):
    if FERRET and name=="f":
        out.append(".set scal_f,scal_b");continue
    out.append("        .even")
    out.append("scal_%s:" % name)
    for i in range(0, NL, 8):
        out.append("        .long " + ",".join("s%s_%d" % (name, q) for q in range(i, i + 8)))
qt = []
for i in range(32768):
    z = (i + 0.5) / 1024.0
    q = int(round(math.log(z / Z0) / math.log(R))) if z > 0 else 0
    qt.append(max(0, min(NL - 1, q)))
out.append("scal_q:")
for i in range(0, len(qt), 32):
    out.append("        .byte " + ",".join(str(x) for x in qt[i:i + 32]))
out.append("        .even")
# Native scalers use a fixed horizon rather than an origin reset at each clip.
NATIVE_LEVELS = 160
native_ratio = (Z1 / Z0) ** (1 / (NATIVE_LEVELS - 1))
out += ["#ifdef DREAD_NATIVE_PERSPECTIVE", ".globl native_b, native_f, native_offsets_b, native_offsets_f"]
for name, ns in (("b", 72), ("f", 144)):
    for q in range(NATIVE_LEVELS):
        step = Z0 * native_ratio ** q
        offsets = [int(math.floor((y - ns/2) * step + .5)) for y in range(ns)]
        if name=="f":out.append("#ifndef DREAD_GAMEPLAY")
        out.append("native_%s_%d:" % (name, q))
        for y, off in enumerate(offsets):
            # MOVE.B disp(a1),disp(a0); DBRA d6,+4 (skip RTS); RTS.
            out.append(" .word 0x1169,%d,%d,0x51ce,4,0x4e75" % (off, y*4))
        out.append(" .word 0x4e75")
        if name=="f":out.append("#endif")
        out.append("native_off_%s_%d:" % (name, q))
        for i in range(0, ns, 16):
            out.append(" .word " + ",".join(map(str, offsets[i:i+16])))
    out.append("native_%s:" % name)
    if name=="f":out.extend(["#ifdef DREAD_GAMEPLAY", " .rept %d" % NATIVE_LEVELS, " .long 0", " .endr", "#else"])
    out.append(" .long " + ",".join("native_%s_%d" % (name,q) for q in range(NATIVE_LEVELS)))
    if name=="f":out.append("#endif")
    out.append("native_offsets_%s:" % name)
    out.append(" .long " + ",".join("native_off_%s_%d" % (name,q) for q in range(NATIVE_LEVELS)))
out.append(" .globl native_zq72, native_zq144, native_steps")
out.append("native_steps:")
out.append(" .word " + ",".join(str(min(32766,round(1024*Z0*native_ratio**q))) for q in range(NATIVE_LEVELS)))
for vh, focal in ((72,90),(144,179)):
    out.append("native_zq%d:" % vh)
    values=[]
    for i in range(32768):
        step=4194304 / ((i*32+16)*focal)
        values.append(max(0,min(NATIVE_LEVELS-1,round(math.log(step/Z0)/math.log(native_ratio)))))
    for i in range(0,32768,32):out.append(" .byte " + ",".join(map(str,values[i:i+32])))
out.append("#endif")
open(sys.argv[1], "w").write("\n".join(out) + "\n")
print("scalers: %d levels, step ratio %.4f" % (NL, R))
