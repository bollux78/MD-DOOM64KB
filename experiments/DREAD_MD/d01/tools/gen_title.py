#!/usr/bin/env python3
"""DREAD-MD: the user's 32-colour Doom title image (320x224) -> 2 x 16-colour palettes + per-tile choice.
Same method as the Manifold menu (gen_assets.py). usage: gen_title.py title.png OUT.c"""
import sys, random, collections
from PIL import Image

src = Image.open(sys.argv[1])
sp = src.getpalette()[:96]
rgb = [tuple(sp[i * 3:i * 3 + 3]) for i in range(32)]
lv = lambda v: min(7, round(v / 36.4))
md = lambda c: (lv(c[2]) << 9) | (lv(c[1]) << 5) | (lv(c[0]) << 1)
W, H = src.size
pix = list(src.getdata())
X = collections.Counter(pix).most_common(1)[0][0]
tiles_px = [[pix[(ty * 8 + y) * W + tx * 8 + x] for y in range(8) for x in range(8)] for ty in range(H // 8) for tx in range(W // 8)]
d2 = lambda a, b: sum((x - y) ** 2 for x, y in zip(rgb[a], rgb[b]))
random.seed(1)
assign = [random.randint(0, 1) for _ in tiles_px]
pals = [list(range(16)), list(range(16, 32))]
cost = lambda t, pal: sum(min(d2(c, p) for p in pal) for c in t)
for it in range(12):
    for k in (0, 1):
        cnt = collections.Counter(c for t, a in zip(tiles_px, assign) if a == k for c in t)
        chosen = [X]
        while len(chosen) < min(16, len(cnt) + 1):
            best = None
            for c in cnt:
                if c in chosen: continue
                tr = chosen + [c]
                e = sum(n * min(d2(x, p) for p in tr) for x, n in cnt.items())
                if best is None or e < best[0]: best = (e, c)
            if best is None: break
            chosen.append(best[1])
        while len(chosen) < 16: chosen.append(chosen[0])
        pals[k] = chosen
    new = [0 if cost(t, pals[0]) <= cost(t, pals[1]) else 1 for t in tiles_px]
    if new == assign: break
    assign = new
tiles = []
for t, a in zip(tiles_px, assign):
    rows = []
    for y in range(8):
        r = 0
        for x in range(8):
            r = (r << 4) | min(range(16), key=lambda i: d2(t[y * 8 + x], pals[a][i]))
        rows.append(r)
    tiles.append(rows)
o = ["/* generated by gen_title.py */", '#include "mapdata.h"',
     "const uint16_t title_w = %d, title_h = %d;" % (W // 8, H // 8),
     "const uint16_t title_pal[32] = {%s};" % ",".join("0x%04X" % md(rgb[c]) for k in (0, 1) for c in pals[k]),
     "const uint8_t title_attr[%d] = {%s};" % (len(assign), ",".join(map(str, assign))),
     "const uint32_t title_tiles[%d] = {%s};" % (len(tiles) * 8, ",".join("0x%08X" % r for t in tiles for r in t))]
open(sys.argv[2], "w").write("\n".join(o) + "\n")
print("title: %d tiles" % len(tiles))
