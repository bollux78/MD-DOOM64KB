#!/usr/bin/env python3
"""DREAD-MD opening image: the R128 title (assets/art/r78-title.png, the user's picture), lossless:
BG_B opaque base + BG_A sparse exact correction, 4 palettes (scripts/lab/gen_r78_art.py encoder).
usage: gen_title.py OUT.c"""
import sys, json, struct, importlib.util
from pathlib import Path
ROOT = Path(__file__).resolve().parents[4]
spec = importlib.util.spec_from_file_location("r78", ROOT / "scripts/lab/gen_r78_art.py")
R = importlib.util.module_from_spec(spec); spec.loader.exec_module(R)
cfg = json.loads((ROOT / "assets/art/r78-palettes.json").read_text())["title"]
blobs, decoded, report = R.encode(ROOT / "assets/art" / cfg["file"], cfg)
pack = blobs["pack"]
ma = struct.unpack(">1120H", blobs["map"]); mb = struct.unpack(">1120H", blobs["mapb"]); pal = struct.unpack(">64H", blobs["pal"])
words = struct.unpack(">%dI" % (len(pack) // 4), pack)
o = ["/* generated by gen_title.py from assets/art/r78-title.png (lossless, 2 planes, 4 palettes) */", '#include "mapdata.h"',
     "const uint16_t title_ntiles = %d;" % (len(pack) // 32),
     "const uint16_t title_pal[64] = {%s};" % ",".join("0x%04X" % v for v in pal),
     "const uint16_t title_mapa[1120] = {%s};" % ",".join(map(str, ma)),
     "const uint16_t title_mapb[1120] = {%s};" % ",".join(map(str, mb)),
     "const uint32_t title_tiles[%d] = {%s};" % (len(words), ",".join("0x%08X" % w for w in words))]
Path(sys.argv[1]).write_text("\n".join(o) + "\n")
print("title: %d tiles (lossless R128 opening)" % (len(pack) // 32))
