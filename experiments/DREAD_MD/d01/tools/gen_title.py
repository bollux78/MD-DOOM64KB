#!/usr/bin/env python3
"""DREAD-MD opening image: the user's title (Tile Palette Studio export, "REPROGRAMMED BY BOLLUX78"),
4 palettes with a per-tile palette CSV (same method as Manifold gen_credits.py). usage: gen_title.py OUT.c"""
import csv, struct, sys
from pathlib import Path
from PIL import Image
D = Path(__file__).resolve().parent / "title_src"
name = "titlescreenBOLLUX"
im = Image.open(D / (name + "_pal.png")).convert("RGBA")
pal_of = {(int(r["tile_x"]), int(r["tile_y"])): int(r["palette_0_to_3"]) for r in csv.DictReader(open(D / (name + "_pal_tile_palettes.csv")))}
px = im.load()
# the export's 4 palettes = the colours of the tiles assigned to each one (15 each), index 0 = backdrop
groups = [set() for _ in range(4)]
for (tx, ty), p in pal_of.items():
    for y in range(8):
        for x in range(8): groups[p].add(px[tx * 8 + x, ty * 8 + y][:3])
lv = lambda v: max(0, min(7, round(v / 36.43)))
pr, cram = [], []
for g in groups:
    cols = [(0, 0, 0)] + sorted(g, key=lambda c: sum(c))[:15]
    while len(cols) < 16: cols.append((0, 0, 0))
    pr.append(cols)
    cram += [(lv(c[2]) << 9) | (lv(c[1]) << 5) | (lv(c[0]) << 1) for c in cols]
menu = "--menu" in sys.argv[2:]
if menu:
    # SGDK's font uses ink 15. Palette 3 shares its last entry with the menu.
    pr[3][15] = (255, 255, 255)
    cram[63] = 0x0EEE
mapb, words = [], []
for ty in range(28):
    for tx in range(40):
        p = pal_of[(tx, ty)]
        mapb.append((p << 13) | (ty * 40 + tx))
        for y in range(8):
            row = 0
            for x in range(8):
                r, g, b, a = px[tx * 8 + x, ty * 8 + y]
                best = min(range(1, 16), key=lambda i: (pr[p][i][0] - r) ** 2 + (pr[p][i][1] - g) ** 2 + (pr[p][i][2] - b) ** 2)
                row = (row << 4) | best
            words.append(row)
o = ["/* generated by gen_title.py from title_src/titlescreenBOLLUX (4 palettes, per-tile CSV) */", '#include "mapdata.h"',
     "const uint16_t title_ntiles = 1120;",
     "const uint16_t title_pal[64] = {%s};" % ",".join("0x%04X" % v for v in cram),
     "const uint16_t title_mapa[1120] = {0};",
     "const uint16_t title_mapb[1120] = {%s};" % ",".join(map(str, mapb)),
     "const uint32_t title_tiles[%d] = {%s};" % (len(words), ",".join("0x%08X" % w for w in words))]
Path(sys.argv[1]).write_text("\n".join(o) + "\n")
print("title: 1120 tiles (titlescreenBOLLUX)")
