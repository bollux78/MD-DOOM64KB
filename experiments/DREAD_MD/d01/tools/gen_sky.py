#!/usr/bin/env python3
"""Sky for DREAD-MD: the user's 256x72 grey sky (Manifold r064, vertical-line dither) -> sky.c.
Each byte holds two neighbouring sky pixels (one framebuffer pair), each mapped to the nearest colour of
the map's MD palette. 128 columns x (72 rows + 4 pad), column-major; 128 columns = 90 degrees (Doom).
usage: gen_sky.py SKY.png GENERATED.c(with md_palette) OUT.c"""
import re, sys
from PIL import Image

DAC = [0, 52, 87, 116, 144, 172, 206, 255]
src = open(sys.argv[2]).read()
body = re.search(r"md_palette\[\d+\]\[16\] = \{\{([^}]*)\}", src).group(1)
pal = []
for v in re.findall(r"0x([0-9A-Fa-f]+)", body)[:16]:
    c = int(v, 16)
    pal.append((DAC[(c >> 1) & 7], DAC[(c >> 5) & 7], DAC[(c >> 9) & 7]))
im = Image.open(sys.argv[1]).convert("RGB")
W, H = im.size
def nearest(rgb):
    return min(range(16), key=lambda i: sum((a - b) ** 2 for a, b in zip(rgb, pal[i])))
cache = {}
out = []
PAD = 4
for x in range(0, W, 2):
    col = []
    for y in range(H):
        a, b = im.getpixel((x, y)), im.getpixel((x + 1, y))
        ia = cache.setdefault(a, nearest(a)); ib = cache.setdefault(b, nearest(b))
        col.append((ia << 4) | ib)
    col += [col[-1]] * PAD
    out += col
open(sys.argv[3], "w").write("/* generated by gen_sky.py */\n#include <types.h>\nconst u8 sky_blob[%d] = {%s};\n" % (len(out), ",".join(map(str, out))))
print("sky: %d columns x %d rows" % (W // 2, H))
