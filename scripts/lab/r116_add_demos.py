#!/usr/bin/env python3
"""R116 demo tests: append per-map test demos to the converted WAD and write src/r116_demos.h.

The demos are third-party recordings (DSDA UV-Max, Doom v1.9 format). They are NOT in git: the
runner reads them from a private folder (--dir) and checks each file against the sha256 pinned in
the manifest. Only the test ROM embeds them, and that ROM is copied to a private runner folder,
never uploaded as a public artifact.

Lumps appended at the end of the directory (existing lump numbers do not change):
  DTE1M1 .. DTE1M9  primary UV-Max demo of each map (manifest "primary": true)
  DTE1M6S           generated E1M6 "special": skill UV in the header, so the R115 cap spawns the
                    Hurt Me Plenty thing set. Deterministic wander/fire/use input, 4,200 tics,
                    deaths respawn the level (use). No answer key: it checks the capped map runs
                    with combat and level reloads, and records its own results for regressions.
Index in src/r116_demos.h: 1..9 = DTE1M1..DTE1M9, 10 = DTE1M6S.
"""
import argparse, hashlib, json, pathlib, struct

SPECIAL_TICS = 4200


def special_demo():
    """Deterministic E1M6 input: header = v1.9, UV, E1, M6, single player."""
    out = bytearray([109, 3, 1, 6, 0, 0, 0, 0, 0, 1, 0, 0, 0])
    x = 0x2611_0201
    def rnd(n):
        nonlocal x
        x = (x * 1103515245 + 12345) & 0x7FFFFFFF
        return (x >> 8) % n
    t = 0
    while t < SPECIAL_TICS:
        seg = 15 + rnd(46)
        fwd = (50, 50, 50, 25, -25)[rnd(5)]
        side = (0, 0, 0, 40, -40)[rnd(5)]
        turn = rnd(13) - 6
        fire = rnd(10) < 7
        for _ in range(seg):
            if t >= SPECIAL_TICS: break
            b = 1 if fire else 0                # BT_ATTACK
            if t % 10 == 5: b |= 2              # BT_USE: doors, switches, respawn after death
            if t % 300 == 40: b |= 4 | (2 << 3)    # BT_CHANGE to shotgun (ignored if not owned)
            if t % 300 == 190: b |= 4 | (3 << 3)   # BT_CHANGE to chaingun
            out += struct.pack('bbBB', fwd, side, turn & 0xFF, b)
            t += 1
    out.append(0x80)
    return bytes(out)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--wad', required=True); ap.add_argument('--dir', required=True)
    ap.add_argument('--manifest', required=True); ap.add_argument('--header', required=True)
    a = ap.parse_args()
    man = json.loads(pathlib.Path(a.manifest).read_text())
    prim = {d['map']: d for d in man['demos'] if d['primary']}
    assert sorted(prim) == list(range(1, 10)), sorted(prim)
    lumps, rows = [], [None] * 11
    for m in range(1, 10):
        d = prim[m]; p = pathlib.Path(a.dir) / d['file']
        b = p.read_bytes()
        assert hashlib.sha256(b).hexdigest() == d['sha256'], ('sha256 mismatch', d['file'])
        h = b[:13]
        assert h[0] == 109 and h[1] == 3 and h[2] == 1 and h[3] == m and h[4:9] == bytes(5) and list(h[9:13]) == [1, 0, 0, 0], (d['file'], list(h))
        assert b[-1] == 0x80 and (len(b) - 14) % 4 == 0 and len(b) < 65536, d['file']
        lumps.append(('DTE1M%d' % m, b))
        rows[m] = dict(lump='DTE1M%d' % m, map=m, nocap=d['nocap'], want=d['want_leveltime'],
                       label=('E1M%d %s %s' % (m, d['player'], d['dsda_time'])).upper()[:32])
    sp = special_demo(); lumps.append(('DTE1M6S', sp))
    rows[10] = dict(lump='DTE1M6S', map=6, nocap=0, want=0, label='E1M6 SPECIAL UV CAP (HMP SET)')
    # Append lumps after the whole old file (4-aligned), then a new directory (old + new entries).
    w = bytearray(pathlib.Path(a.wad).read_bytes())
    n = struct.unpack_from('>h', w, 4)[0]; ofs = struct.unpack_from('>i', w, 8)[0]
    dirb = bytes(w[ofs:ofs + 16 * n]); names = {dirb[i*16+8:i*16+16].rstrip(b'\0') for i in range(n)}
    out = bytearray(w); ents = []   # keep every old byte; repack_wad re-lays the data from the directory
    for name, data in lumps:
        assert name.encode() not in names, name
        while len(out) % 4: out.append(0)
        ents.append(struct.pack('>iHh8s', len(out), len(data), 0, name.encode()))
        out += data
    while len(out) % 4: out.append(0)
    newofs = len(out); out += dirb + b''.join(ents)
    struct.pack_into('>h', out, 4, n + len(lumps)); struct.pack_into('>i', out, 8, newofs)
    pathlib.Path(a.wad).write_bytes(out)
    # Header for the ROM (labels are plain ASCII, quoted safely).
    def q(s): return '"' + ''.join(c if (c.isalnum() or c in ' :.-()/') else ' ' for c in s) + '"'
    hl = ['/* Generated by scripts/lab/r116_add_demos.py. R116 demo tests (test ROM only). */',
          '#ifndef R116_DEMOS_H', '#define R116_DEMOS_H', '#include <stdint.h>',
          'typedef struct { const char *lump; const char *label; uint16_t want; uint8_t map; uint8_t nocap; } r116_demo_t;',
          'typedef struct { int32_t exit_time; uint32_t exit_gametic; int16_t kills,tkills,items,titems,secrets,tsecrets;',
          '                 uint16_t zmin_total,zmin_largest,deaths; uint8_t map,secretexit,sel,done; uint8_t pad[2]; } r116_res_t;',
          'extern r116_res_t r116_res;',
          '#define R116_DEMO_COUNT 10',
          'static const r116_demo_t __attribute__((unused)) r116_demos[R116_DEMO_COUNT+1] = {', '    {0,0,0,0,0},']
    for r in rows[1:]:
        hl.append('    {%s,%s,%du,%du,%du},' % (q(r['lump']), q(r['label']), r['want'], r['map'], r['nocap']))
    hl += ['};', '#endif', '']
    pathlib.Path(a.header).write_text('\n'.join(hl))
    print('R116 demos:', ' '.join('%s=%dB' % (nm, len(d)) for nm, d in lumps), 'special sha256', hashlib.sha256(sp).hexdigest()[:16])


if __name__ == '__main__':
    main()
