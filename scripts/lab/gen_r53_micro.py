#!/usr/bin/env python3
"""R53 offline 1px micro-dither companions, per VDP palette (not PAL0/PAL1 cross-blending).

Run after gen_r52_claudio.py, before build. Keeps the 76x44 framebuffer and
the two 4-pixel logical column samples intact. No runtime color search.
"""
from __future__ import annotations
import argparse, json, runpy
from pathlib import Path
import numpy as np

def build(repo: Path, profile: str, out: Path, ratio: int) -> None:
    assert ratio in (25, 50)
    g = runpy.run_path(str(repo / "scripts/lab/gen_r52_claudio.py"))
    gp = runpy.run_path(str(repo / "scripts/genpal.py"))
    rep = json.loads((out / "r52_ab_report.json").read_text())
    assert rep["args"]["mode"] == profile
    src = np.asarray(gp["decode_subpal"](gp["load_playpal"](), 0), dtype=float)
    lumps = g["wad_lumps"]((repo / "scripts/doom64.wad").read_bytes())
    cm = next((blob for name, blob in lumps if name == "COLORMAP"), None)
    assert cm is not None and len(cm) % 256 == 0
    weights = g["proxy_histogram"](lumps, 0.7, range(6, 23), 0.35, np.frombuffer(cm, dtype=np.uint8))
    weights = np.asarray(weights, dtype=float)
    assert np.isfinite(weights).all() and 0.99 <= weights.sum() <= 1.01
    results = []
    partners = []
    for plane, key, mapkey in [("even", "pal0", "even"), ("odd", "pal1", "odd")]:
        colors = np.zeros((16, 3), float)
        slots = rep["palette_slots"][key]
        assert len(slots) == 15
        for slot in slots:
            colors[int(slot["slot"])] = np.asarray(slot["rgb"],float)
        indices = np.asarray(rep["parity_maps"][mapkey], dtype=np.uint8)
        assert len(indices)==256 and np.max(indices)<=15
        mapping = list(range(16))
        accepted = []
        for i in range(1,16):
            where = np.where(indices == i)[0]
            if not len(where):continue
            w = weights[where]
            if w.sum() <= 0:continue
            base = colors[i]
            base_lab = g["to_lab"](base)
            base_error = g["delta_e"](src[where], base)
            best_loss = float(np.sum(base_error * w))
            best_index = i
            winner_loss = best_loss
            for j in range(1,16):
                if j==i:continue
                contrast=float(g["delta_e"](base,colors[j]))
                dluma=float(abs(g["luma"](base)-g["luma"](colors[j])))
                # Prevent checkerboard accent colours and bright/dark flicker on CRT.
                if contrast>38 or dluma>38:continue
                blend = g["lin2srgb"]((1-ratio/100)*g["srgb2lin"](base)
                                          +(ratio/100)*g["srgb2lin"](colors[j]))
                e = g["delta_e"](src[where],blend)
                # Penalty: favour local colour neighbours, even where averaged Lab improves.
                loss=float(np.sum(e*w)) + (contrast/38)**2*0.10*float(w.sum())
                if loss + 1e-7 < winner_loss:
                    winner_loss=loss;best_index=j
            if best_index!=i and winner_loss < best_loss - max(0.015,0.012*best_loss):
                mapping[i]=best_index
                accepted.append(dict(base=i,companion=best_index,
                                     contrast_dE=round(float(g["delta_e"](base,colors[best_index])),2),
                                     weight=round(float(w.sum()),5),
                                     weighted_error_delta=round(best_loss-winner_loss,5)))
        assert mapping[0]==0 and all(0<=x<=15 for x in mapping)
        partners.append(mapping)
        results.append(dict(plane=plane,accepted=accepted,active=len(accepted)))
    text=["/* R53 generated by gen_r53_micro.py: source PAL0/PAL1, fixed index companions. */",
          "#ifndef DOOM_R53_MICRO_TABLES_H","#define DOOM_R53_MICRO_TABLES_H","#include <stdint.h>"]
    for name,arr in zip(("r53_partner_even","r53_partner_odd"),partners):
        text.append("static const uint8_t "+name+"[16]={"+",".join(str(x) for x in arr)+"};")
    text.append("#endif")
    (out/"r53_micro_tables.h").write_text("\n".join(text)+"\n")
    report={"generator":"gen_r53_micro.py","ratio_percent":ratio,"palette_profile":profile,
            "zero_policy":rep["args"]["zero_policy"],"companion_maps":
                {"even":partners[0],"odd":partners[1]},"selection":results,
            "method":"per-base slot, proxy-weighted subpalette0 Lab error; contrast <=38 dE; luma <=38",
            "disclaimer":"1 physical-pixel microdither within PAL0 or PAL1, not alternating PAL0/PAL1 per pixel."}
    (out/"r53_micro_report.json").write_text(json.dumps(report,indent=2)+"\n")
    print("R53 micro partner active",profile,ratio,[p["active"] for p in results],
          "maps",partners)
    
if __name__=="__main__":
    ap=argparse.ArgumentParser()
    ap.add_argument("--repo",default=".")
    ap.add_argument("--profile",choices=["near25","luma32","free"],required=True)
    ap.add_argument("--out",default="src")
    ap.add_argument("--ratio",type=int,choices=[25,50],required=True)
    a=ap.parse_args()
    build(Path(a.repo).resolve(),a.profile,Path(a.out),a.ratio)
