#!/usr/bin/env python3
"""Isolated, exact-image candidates AFTER the complete R113 chain. Never alter SRAM/IRQ code.
R114_CANDIDATE: depth, sprite, subos, subiv, combo. Control is the untouched R113.
"""
from pathlib import Path
import os


def replace(path, old, new):
    p = Path(path); s = p.read_text()
    assert s.count(old) == 1, (path, old[:100], s.count(old))
    p.write_text(s.replace(old, new))


def depth_tables(width=76, height=44):
    # Separate arrays avoid a 12-byte struct index in the 68000 hot path.
    arrays = dict(xscale=[], yscale=[], iscale=[])
    for z in range(1281):
        x = ((width // 2) << 16) // z if z else 0
        arrays['xscale'].append(x)
        arrays['yscale'].append((height << 16) // z if z else 0)
        arrays['iscale'].append(0xffffffff // x if x else 0)
    return arrays


def main():
    mode = os.environ['R114_CANDIDATE']
    assert mode in ('depth', 'sprite', 'subos', 'subiv', 'combo')
    assert Path('src/r113_hilut_wall.s').is_file(), 'apply R113 first'
    if mode in ('depth', 'combo'):
        out = ['/* Exact integer projection: generated by apply_r114.py. ROM only. */',
               '#if VIEWWINDOWWIDTH != 76 || VIEWWINDOWHEIGHT != 44',
               '#error R114 projection table requires the R113 76x44 renderer', '#endif']
        for name, values in depth_tables().items():
            out.append('static const uint32_t r114_%s[1281] = {\n%s\n};' %
                       (name, ',\n'.join(','.join(str(v)+'u' for v in values[i:i+12]) for i in range(0,len(values),12))))
        Path('src/r114_depth_tables.h').write_text('\n'.join(out)+'\n')
        d = 'src/r_draw.c'
        replace(d, '#define MAXZ        (FRACUNIT*1280)', '#define MAXZ        (FRACUNIT*1280)\n#include "r114_depth_tables.h"')
        replace(d, 'const fixed_t xscale = PROJECTION / (tz >> FRACBITS);',
                'const fixed_t xscale = (fixed_t)r114_xscale[(uint16_t)(tz >> FRACBITS)];')
        replace(d, 'vis->scale           = (VIEWWINDOWHEIGHT * FRACUNIT) / (tz >> FRACBITS);',
                'vis->scale           = (fixed_t)r114_yscale[(uint16_t)(tz >> FRACBITS)];')
        replace(d, 'const fixed_t iscale = FixedReciprocal(xscale);',
                'const fixed_t iscale = (fixed_t)r114_iscale[(uint16_t)(tz >> FRACBITS)];')
        # fracstep intentionally retains the full fixed-point tz; no quantization is introduced.
    elif mode == 'sprite':
        d = 'src/r22_video.inc'
        replace(d, '#include "r64a_ctx.h"', '#include "r64a_ctx.h"\n#include "r113_hilut_wall.h"')
        replace(d, '    if(!colormap && count>=2u){\n        R60_WallDraw(dst,source,r52map,frac,step,count,(uint16_t)(first&1u));',
                '''    /* Only R52_LUT's composed tables have the +8704 shifted twin.
     * Fuzz and arbitrary/uncomposed maps retain their original paths. */
    if(r52fast && count>=2u){
        R113_WallDraw(dst,source,r52map,frac,step,count,(uint16_t)(first&1u));
        return;
    }
    if(!colormap && count>=2u){
        R60_WallDraw(dst,source,r52map,frac,step,count,(uint16_t)(first&1u));''')
    else:
        option = 'Os' if mode == 'subos' else 'no-ivopts'
        replace('src/r_draw.c', 'static void R_Subsector(int16_t num)',
                'static void __attribute__((optimize("%s"))) R_Subsector(int16_t num)' % option)
    if mode == 'combo':
        replace('src/r_draw.c', 'static void R_Subsector(int16_t num)',
                'static void __attribute__((optimize("no-ivopts"))) R_Subsector(int16_t num)')
    replace('scripts/lab/build_r71a12mul_hud.py', "'r113-'", "'r115-'" if mode == 'combo' else "'r114-'")
    replace('scripts/lab/build_r71a12mul_hud.py', "('hilut', 1)", "('%s', 1)" % mode)
    print('R114 isolated candidate:', mode)


if __name__ == '__main__':
    main()
