#!/usr/bin/env python3
"""R76 four complete runtime R59-style profiles, zero new render-loop math.

Profiles:
  HB = L32F-M50 L3 walls/sprites/CRAM, HN flats with selected blue A2-target flat codes
  A2 = N25A-M50 F2 full CRAM + companions + walls/sprites
  L3 = L32F-M50 F3 full CRAM + companions + walls/sprites
  HN = L32F-M50 L3 full CRAM, R75-HN flat-only mapping

Called after R75 'near' generator in the same isolated runner checkout.
"""
from pathlib import Path
import hashlib,json,re,runpy,subprocess,sys
import numpy as np

ROOT=Path(__file__).resolve().parents[2]
SRC=ROOT/'src'
A2=ROOT/'dist/r75_a2_target'
assert all((A2/p).is_file() for p in ('r52_ab_tables.h','r53_micro_tables.h','r74_flat_tables.h'))
assert all((SRC/p).is_file() for p in ('r52_ab_tables.h','r53_micro_tables.h','r74_flat_tables.h','r75_hybrid_flats.h'))
aux=runpy.run_path(str(ROOT/'scripts/lab/gen_r74_flats.py'))
arr=aux['array']
gp=runpy.run_path(str(ROOT/'scripts/genpal.py'))

def load(path,flat_source):
    h=(path/'r52_ab_tables.h').read_text()
    micro=(path/'r53_micro_tables.h').read_text()
    flats=(path/'r74_flat_tables.h').read_text()
    banks=[arr(h,'r52_pal'+str(p)) for p in (0,1)]
    maps=[arr(h,'r52_'+side) for side in ('even','odd')]
    comps=[arr(h,'r52_comp_'+side) for side in ('even','odd')]
    partners=[arr(micro,'r53_partner_'+side) for side in ('even','odd')]
    flat=[arr(flats,'r74_flat_'+side) for side in ('even','odd')]
    assert all(len(q)==224 for q in banks)
    assert all(len(q)==256 for q in maps+flat)
    assert all(len(q)==16 and q[0]==0 for q in partners)
    assert len(comps[0])==len(comps[1]) and len(comps[0])%256==0
    return dict(pal=banks,wall=maps,comp=comps,partners=partners,flat=flat,origin=flat_source)

A=load(A2,'N25A-M50 F2')
L=load(SRC,'L32F-M50 F3')
HN=[arr((SRC/'r75_hybrid_flats.h').read_text(),'r75_flat_'+k).astype(np.uint8) for k in ('even','odd')]
# Derive a second L3-CRAM flat mapping optimized more directly toward A2;
# only these 512 bytes differ from HN/L3. Save HN first.
subprocess.run([sys.executable,str(ROOT/'scripts/lab/gen_r75_hybrid.py'),'a2'],cwd=ROOT,check=True)
H2=[arr((SRC/'r75_hybrid_flats.h').read_text(),'r75_flat_'+k).astype(np.uint8) for k in ('even','odd')]
original=np.asarray(gp['decode_subpal'](gp['load_playpal'](),0),float)
blue=(original[:,2]>original[:,0]*1.18)&(original[:,2]>original[:,1]*1.12)&(original[:,2]>42)&((original[:,2]-original[:,0])>19)
# Selection is indexed by the exact Doom color c arriving at R_DrawColumnFlat.
HB=[np.where(blue,H2[side],HN[side]).astype(np.uint8) for side in (0,1)]
for p,table in [('A2',A['flat']),('L3',L['flat']),('HN',HN),('HB',HB)]:
    assert all(len(x)==256 and x.min()>=0 and x.max()<=15 for x in table),p
print('R76 blue flat indices',int(blue.sum()),'A2-targeted vs HN',flush=True)

def emit(name,values,typ='uint8_t',row=None):
    values=[int(v) for v in values]
    if row:
        assert len(values)%row==0
        lines=[' {'+','.join(map(str,values[i:i+row]))+'}' for i in range(0,len(values),row)]
        return 'static const '+typ+' '+name+'['+str(len(values)//row)+']['+str(row)+']={\n'+',\n'.join(lines)+'\n};'
    return 'static const '+typ+' '+name+'['+str(len(values))+']={\n'+','.join(map(str,values))+'\n};'

body=['/* Generated by gen_r76_profiles.py; fixed full A2 and L3 CRAM. */',
      '#ifndef R59_COLOR_TABLES_H','#define R59_COLOR_TABLES_H',
      '#include <stdint.h>','#define R59_COLOR_MODES 4']
for tag,profile in [('a',A),('l',L)]:
    for side,n in [('even',0),('odd',1)]:
        body.append(emit('r76_'+tag+'_wall_'+side,profile['wall'][n]))
        body.append(emit('r76_'+tag+'_comp_'+side,profile['comp'][n],row=256))
        vals=np.asarray([[i,int(profile['partners'][n][i])] for i in range(16)],dtype=np.uint8).flatten()
        body.append(emit('r76_'+tag+'_pairs_'+side,vals,row=2))
        body.append(emit('r76_'+tag+'_pal'+str(n),profile['pal'][n],'uint16_t',row=16))
for tag,tables in [('a',A['flat']),('l',L['flat']),('n',HN),('b',HB)]:
    for side,n in [('even',0),('odd',1)]:
        body.append(emit('r76_'+tag+'_flat_'+side,tables[n]))
body.extend([
    'typedef struct {',
    ' const uint16_t (*pal0)[16],(*pal1)[16];',
    ' const uint8_t (*pairs_even)[2],(*pairs_odd)[2];',
    ' const uint8_t *wall_even,*wall_odd,*flat_even,*flat_odd;',
    ' const uint8_t (*comp_even)[256],(*comp_odd)[256];',
    '} R59ColorTables;',
    'static const R59ColorTables r59_color_tables[R59_COLOR_MODES]={'
])
for label,pal,flat in [('b','l','b'),('a','a','a'),('l','l','l'),('n','l','n')]:
    prefix='r76_'+pal+'_'
    line='{'+','.join((prefix+'pal0',prefix+'pal1',
         prefix+'pairs_even',prefix+'pairs_odd',
         prefix+'wall_even',prefix+'wall_odd',
         'r76_'+flat+'_flat_even','r76_'+flat+'_flat_odd',
         prefix+'comp_even',prefix+'comp_odd'))+'}'
    body.append(' '+line+',' if label!='n' else ' '+line)
body.extend(['};','#endif'])
dest=SRC/'r59_color_tables.h'
dest.write_text('\n'.join(body)+'\n')
report=dict(modes=['Hybrid Blue (L3/HN+A2 blue flats)','A2 N25A-M50 F2','L3 L32F-M50 F3','HN L32F-M50 near flats'],
            blue_code_count=int(blue.sum()),blue_source_codes=np.flatnonzero(blue).tolist(),
            generated_sha256=hashlib.sha256(dest.read_bytes()).hexdigest(),
            source='R52+R53 M50 regenerated from pinned WAD; A2 and L3 palettes kept independent',
            all_modes_use_full_matching_cram_and_pair_patterns=True,
            warning='Hybrid uses L3 CRAM; red enemy cannot become exact A2 red within that CRAM.')
(SRC/'r76_profiles_report.json').write_text(json.dumps(report,indent=2)+'\n')
print('R76 generated four mode table, bytes',dest.stat().st_size,report['generated_sha256'],flush=True)
