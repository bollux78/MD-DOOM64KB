#!/usr/bin/env python3
"""Generate an exact 4096-entry ROM tangent lookup from original r_draw.c tables.

This is intentionally a ROM-vs-CPU tradeoff: 4096 * 4 = 16 KiB of ROM,
no additional work RAM. Never approximate or recompute tangent values.
"""
from pathlib import Path
import re

ROOT = Path(__file__).resolve().parent.parent
SOURCE = ROOT / "src" / "r_draw.c"
DEST = ROOT / "src" / "wall_tangent_lut.h"


def get_table(text: str, name: str) -> list[int]:
    # r_draw.c declares part_4 twice in a preprocessor #if/#else, both
    # followed by the SAME initializer. Use its final declaration.
    marker = name + "[1024] ="
    start = text.rfind(marker)
    if start < 0:
        raise RuntimeError(f"Missing expected original tangent table {name}")
    opening = text.find("{", start)
    closing = text.find("}", opening + 1)
    if opening < 0 or closing < 0:
        raise RuntimeError(f"Malformed original tangent table {name}")
    body = text[opening + 1 : closing]
    if not re.fullmatch(r"[\d\s,]+", body):
        raise RuntimeError(f"Non-numeric source tangent table {name}")
    nums = [int(v) for v in re.findall(r"\d+", body)]
    if len(nums) != 1024:
        raise RuntimeError(f"Expected 1024 elements in {name}, got {len(nums)}")
    if not all(0 <= x <= 0x7FFFFFFF for x in nums):
        raise RuntimeError(f"Unexpected signed 32-bit range in {name}")
    return nums


def main() -> None:
    original = SOURCE.read_text(encoding="utf-8")
    t3 = get_table(original, "finetangentTable_part_3")
    t4 = get_table(original, "finetangentTable_part_4")

    table = []
    for angle in range(4096):
        if angle < 1024:
            tan = t4[1023 - angle]
        elif angle < 2048:
            tan = t3[2047 - angle]
        elif angle < 3072:
            tan = t3[angle - 2048]
        else:
            tan = t4[angle - 3072]
        table.append(tan)

    # Explicit boundaries verify the same 4-quadrant lookup semantics.
    assert len(table) == 4096
    assert table[0] == t4[1023]
    assert table[1023] == t4[0]
    assert table[1024] == t3[1023]
    assert table[2047] == t3[0]
    assert table[2048] == t3[0]
    assert table[3071] == t3[1023]
    assert table[3072] == t4[0]
    assert table[4095] == t4[1023]
    assert table[:2048] == list(reversed(table[2048:]))

    out = [
        "/* AUTO-GENERATED by scripts/gen_wall_tangent_lut.py.",
        " * Source: the original finetangentTable_part_3/4 in r_draw.c.",
        " * Direct positive-magnitude tan lookup for angles 0..4095.",
        " * Add/subtract selection remains in C, preserving shift rounding.",
        " * Stored in ROM, 16384 bytes; never allocate in WRAM.",
        " */",
        "#ifndef DOOM_WALL_TANGENT_LUT_H",
        "#define DOOM_WALL_TANGENT_LUT_H",
        "static const fixed_t doom_wall_tangent_lut[4096] =",
        "{",
    ]
    for i in range(0, len(table), 8):
        out.append("    " + ", ".join(str(v) for v in table[i:i+8]) + ",")
    out.extend(["};", "#endif", ""])
    content = "\n".join(out)
    DEST.write_text(content, encoding="ascii")
    print(f"Wall tangent LUT: verified {len(table)} entries, 16384 ROM bytes")
    print(f"Generated {DEST.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
